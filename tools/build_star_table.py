"""Build src/star_table.rs: the stars with IAU-approved names that have Hipparcos numbers.

Names and visual magnitudes come from the IAU Catalog of Star Names; positions, proper
motions and parallaxes from Hipparcos, the New Reduction (van Leeuwen 2007), queried at
NASA HEASARC (table hipnewcat).

Usage: python3 -I tools/build_star_table.py [src/star_table.rs]
"""
import base64, re, struct, sys, urllib.parse, urllib.request

CSN = "https://www.pas.rochester.edu/~emamajek/WGSN/IAU-CSN.txt"
TAP = "https://heasarc.gsfc.nasa.gov/xamin/vo/tap/sync"
COLS = ["hip_number", "ra", "dec", "pm_ra", "pm_dec", "parallax"]
SIZES = {"int": ">i", "long": ">q", "short": ">h", "double": ">d", "float": ">f"}

def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "astro-calc-fixtures"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return r.read()

def names():
    out = {}
    for line in fetch(CSN).decode("utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        tok = line.split()
        if tok[-1] == "*":
            tok.pop()
        hip, mag = tok[-5], tok[-7]
        if not hip.isdigit():
            continue
        name = line[:18].strip()
        if not all(ord(c) < 128 for c in name):
            continue
        out.setdefault(int(hip), (name, float(mag) if re.fullmatch(r"-?[\d.]+", mag) else None))
    return out

def hipparcos(ids):
    rows = {}
    for i in range(0, len(ids), 100):
        q = f"SELECT {', '.join(COLS)} FROM hipnewcat WHERE hip_number IN ({', '.join(map(str, ids[i:i + 100]))})"
        xml = fetch(TAP + "?" + urllib.parse.urlencode({"REQUEST": "doQuery", "LANG": "ADQL", "QUERY": q})).decode()
        fields = re.findall(r'<FIELD[^>]*?name="([^"]+)"[^>]*?datatype="([^"]+)"|<FIELD[^>]*?datatype="([^"]+)"[^>]*?name="([^"]+)"', xml)
        fields = [(a or d, b or c) for a, b, c, d in fields]
        assert [f[0] for f in fields] == COLS, fields
        data = base64.b64decode(re.search(r"<STREAM[^>]*>(.*?)</STREAM>", xml, re.S).group(1))
        fmt = ">" + "".join(SIZES[t][1] for _, t in fields)
        for rec in struct.iter_unpack(fmt, data):
            rows[rec[0]] = rec[1:]
    return rows

def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "src/star_table.rs"
    named = names()
    cat = hipparcos(sorted(named))
    lines = [
        "// Generated by tools/build_star_table.py; do not edit.",
        "// Names and V magnitudes: IAU Catalog of Star Names. Astrometry: Hipparcos, the New",
        "// Reduction (van Leeuwen 2007), ICRS at epoch J1991.25, via NASA HEASARC.",
        "use crate::stars::Star;",
        "",
        "#[rustfmt::skip]",
        "#[allow(clippy::approx_constant, clippy::excessive_precision)]",
        f"pub(crate) static STARS: [Star; {len(cat)}] = [",
    ]
    for hip in sorted(cat):
        ra, dec, pm_ra, pm_dec, plx = cat[hip]
        name, mag = named[hip]
        mag = "f64::NAN" if mag is None else repr(mag)
        lines.append(f'    Star {{ hip: {hip}, name: "{name}", ra: {ra!r}, dec: {dec!r}, pm_ra: {pm_ra!r}, pm_dec: {pm_dec!r}, parallax: {plx!r}, magnitude: {mag} }},')
    lines.append("];")
    open(out, "w").write("\n".join(lines) + "\n")
    print(f"{len(cat)} stars written to {out}; {len(named) - len(cat)} named stars not found in Hipparcos")

main()
